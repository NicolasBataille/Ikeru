-- ---------------------------------------------------------------------------
-- Triggers
-- ---------------------------------------------------------------------------

do $$
declare t text;
begin
  foreach t in array array[
    'profiles', 'rpg_states', 'cards', 'review_logs',
    'vocabulary_entries', 'vocabulary_encounters',
    'exercise_outcome_logs', 'companion_chat_messages'
  ] loop
    execute format(
      'drop trigger if exists %I on public.%I', t || '_touch_server_updated_at', t);
    execute format(
      'create trigger %I before insert or update on public.%I
         for each row execute function public.touch_server_updated_at()',
      t || '_touch_server_updated_at', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
--
-- This is what makes the publishable key safe to ship inside the app binary.
-- The key identifies the project, it grants nothing: every row carries
-- `user_id`, and every policy compares it to `auth.uid()` from the caller's
-- own verified JWT. Verified for real on 2026-08-13 — a second anonymous user
-- can neither read nor modify the first one's rows.
--
-- The `with_check` on INSERT/UPDATE is not redundant with the `using` clause:
-- `using` decides which rows you may touch, `with_check` decides what the row
-- may look like afterwards. Without it a caller could update a row they own
-- and hand it to somebody else by rewriting `user_id`.

do $$
declare t text;
begin
  foreach t in array array[
    'profiles', 'rpg_states', 'cards', 'review_logs',
    'vocabulary_entries', 'vocabulary_encounters',
    'exercise_outcome_logs', 'companion_chat_messages'
  ] loop
    execute format('alter table public.%I enable row level security', t);

    execute format('drop policy if exists %I on public.%I', t || '_select_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_update_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_delete_own', t);

    execute format(
      'create policy %I on public.%I for select using (auth.uid() = user_id)',
      t || '_select_own', t);
    execute format(
      'create policy %I on public.%I for insert with check (auth.uid() = user_id)',
      t || '_insert_own', t);
    execute format(
      'create policy %I on public.%I for update using (auth.uid() = user_id) with check (auth.uid() = user_id)',
      t || '_update_own', t);
    execute format(
      'create policy %I on public.%I for delete using (auth.uid() = user_id)',
      t || '_delete_own', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------------
--
-- `(user_id, server_updated_at)` is the cursor walk of the original pull.
-- The composite-key migration adds `(user_id, server_updated_at, id)` on top,
-- for the keyset pagination that came later. Both are kept: this file
-- reproduces history, it does not tidy it.

do $$
declare t text;
begin
  foreach t in array array[
    'profiles', 'rpg_states', 'cards', 'review_logs',
    'vocabulary_entries', 'vocabulary_encounters',
    'exercise_outcome_logs', 'companion_chat_messages'
  ] loop
    execute format(
      'create index if not exists %I on public.%I (user_id, server_updated_at)',
      t || '_user_cursor_idx', t);
  end loop;
end $$;

-- Replaying an FSRS card means fetching its logs; without this the query is a
-- scan of the user's whole log table per card.
create index if not exists review_logs_user_card_idx
  on public.review_logs (user_id, card_id);

-- Confusion-pair telemetry (lot 1) reads only rows that recorded what the
-- learner actually answered — a partial index keeps it off the rest.
create index if not exists review_logs_confusion_idx
  on public.review_logs (user_id, answered_value)
  where answered_value is not null;
